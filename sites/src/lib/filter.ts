export function isExcluded(title: string, summary = ""): boolean {
  const text = `${title} ${summary}`.toLowerCase()

  // 强收录信号优先：命中即保留（如 "AI 手机"、"智能驾驶"、"大模型"）
  if (INCLUDE_STRONG.some((k) => text.includes(k))) return false

  // 强排除：命中消费电子硬词直接排除
  for (const kw of EXCLUDE_STRONG_CONSUMER) {
    if (text.includes(kw)) return true
  }

  for (const kw of [...EXCLUDE_LIFE_SCIENCE, ...EXCLUDE_NATURAL_SCIENCE, ...EXCLUDE_CONSUMER]) {
    if (text.includes(kw)) return true
  }
  return false
}
